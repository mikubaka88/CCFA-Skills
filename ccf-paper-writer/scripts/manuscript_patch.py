"""UTF-8 manuscript inventory and hash-bound, section-limited text patches.

This module has no CLI and executes no manuscript code. Offsets count Unicode
characters after removing an optional UTF-8 BOM; newline characters are not
normalized. Sections are nonoverlapping: a heading owns text up to the next
heading of any level. IDs are heading slugs with duplicate suffixes.

Markdown supports ATX and single-line Setext headings outside fenced code.
LaTeX supports literal top-level chapter/section/subsection/subsubsection
commands with balanced titles and optional short titles. Commands nested in a
brace group (for example, a macro definition) are rejected as ambiguous.
Comments and common verbatim
environments are ignored. Macros and included files are not expanded; headings
generated by them are outside this inventory's supported scope.

Replacement strings are literal, including their newline convention. Unedited
bytes, an original BOM, and CRLFs survive unchanged. The sibling lock coordinates
users of this module; it is not a filesystem-wide lock against other editors.
"""

from __future__ import annotations

import hashlib
import os
from pathlib import Path
import re
import secrets
import stat
import tempfile
import unicodedata
from contextlib import contextmanager


class ManuscriptPatchError(ValueError):
    """An invalid, stale, ambiguous, or unauthorized patch was rejected."""


_BOM = b"\xef\xbb\xbf"
_SHA256 = re.compile(r"[0-9a-fA-F]{64}\Z")
_FORMATS = {".md", ".markdown", ".tex"}
_LATEX_HEAD = re.compile(r"\\(chapter|section|subsection|subsubsection)(?![A-Za-z@])")
_VERBATIM = re.compile(r"\\begin\s*\{(verbatim\*?|Verbatim|lstlisting|minted)\}")


def _digest(data):
    return hashlib.sha256(data).hexdigest()


def _hash(value, name):
    if not isinstance(value, str) or not _SHA256.fullmatch(value):
        raise ManuscriptPatchError(f"{name} must be a SHA-256 hex digest")
    return value.lower()


def _plain_path(value, base=None, require_file=True):
    if not isinstance(value, (str, os.PathLike)) or not str(value).strip():
        raise ManuscriptPatchError("a nonempty file path is required")
    candidate = Path(value).expanduser()
    if not candidate.is_absolute():
        candidate = (base or Path.cwd()) / candidate
    # Do not resolve links before checking: doing so would hide their presence.
    candidate = Path(os.path.abspath(candidate))
    for component in (candidate, *candidate.parents):
        if component.is_symlink() or (
            hasattr(component, "is_junction") and component.is_junction()
        ):
            raise ManuscriptPatchError(f"symbolic links/junctions are ambiguous: {component}")
    if require_file and not candidate.is_file():
        raise ManuscriptPatchError(f"not a regular file: {candidate}")
    return candidate


def _read(path):
    try:
        data = path.read_bytes()
        text = (data[len(_BOM):] if data.startswith(_BOM) else data).decode("utf-8")
    except (OSError, UnicodeError) as exc:
        raise ManuscriptPatchError(f"cannot read strict UTF-8 manuscript: {path}: {exc}") from exc
    return data, text


def _markdown_headings(text):
    lines = text.splitlines(keepends=True)
    starts, offset = [], 0
    fence = None
    previous = None
    for line in lines:
        content = line.rstrip("\r\n")
        marker = re.match(r"^ {0,3}(`{3,}|~{3,})(.*)$", content)
        if fence:
            closing = re.match(r"^ {0,3}([`~]+)[ \t]*$", content)
            if closing and set(closing[1]) == {fence[0]} and len(closing[1]) >= fence[1]:
                fence = None
            previous = None
        elif marker and not (marker[1][0] == "`" and "`" in marker[2]):
            fence = (marker[1][0], len(marker[1]))
            previous = None
        else:
            heading = re.match(r"^ {0,3}#{1,6}(?:[ \t]+(.*?)|[ \t]*)$", content)
            setext = re.match(r"^ {0,3}(?:=+|-+)[ \t]*$", content)
            if heading:
                title = re.sub(r"[ \t]+#+[ \t]*$", "", heading[1] or "").strip()
                starts.append((offset, title))
                previous = None
            elif setext and previous:
                starts.append(previous)
                previous = None
            elif content.strip() and not re.match(r"^(?: {4}|\t| {0,3}(?:>|[-+*][ \t]|\d+[.)][ \t]))", content):
                previous = (offset, content.strip())
            else:
                previous = None
        offset += len(line)
    return starts


def _escaped(text, position):
    count = 0
    while position > 0 and text[position - 1] == "\\":
        position -= 1
        count += 1
    return count % 2 == 1


def _mask_latex(text):
    chars = list(text)
    position = 0
    while position < len(text):
        if text[position] == "%" and not _escaped(text, position):
            end = text.find("\n", position)
            end = len(text) if end == -1 else end
            for i in range(position, end):
                if chars[i] not in "\r\n":
                    chars[i] = " "
            position = end
            continue
        if text[position] == "\\" and not _escaped(text, position):
            environment = _VERBATIM.match(text, position)
            if environment:
                close = re.compile(r"\\end\s*\{" + re.escape(environment[1]) + r"\}").search(text, environment.end())
                if close is None:
                    raise ManuscriptPatchError(f"unclosed LaTeX verbatim environment: {environment[1]}")
                for i in range(position, close.end()):
                    if chars[i] not in "\r\n":
                        chars[i] = " "
                position = close.end()
                continue
            inline = re.match(r"\\verb\*?([^A-Za-z\s])", text[position:])
            if inline:
                end = text.find(inline[1], position + inline.end())
                if end == -1 or "\n" in text[position:end]:
                    raise ManuscriptPatchError("unclosed inline LaTeX verb")
                for i in range(position, end + 1):
                    chars[i] = " "
                position = end + 1
                continue
        position += 1
    return "".join(chars)


def _balanced(text, position, opener, closer):
    if position >= len(text) or text[position] != opener:
        raise ManuscriptPatchError("LaTeX heading requires a literal braced title")
    start, depth, braces = position + 1, 1, 0
    for position in range(start, len(text)):
        char = text[position]
        if _escaped(text, position):
            continue
        if opener == "[":
            if char == "{":
                braces += 1
            elif char == "}":
                braces -= 1
            if braces:
                continue
        if char == opener:
            depth += 1
        elif char == closer:
            depth -= 1
            if depth == 0:
                return text[start:position], position + 1
    raise ManuscriptPatchError("unclosed LaTeX heading title")


def _latex_headings(text):
    masked = _mask_latex(text)
    starts = []
    end_of_title = 0
    scanned, brace_depth = 0, 0
    for match in _LATEX_HEAD.finditer(masked):
        if match.start() < end_of_title or _escaped(masked, match.start()):
            continue
        for index in range(scanned, match.start()):
            if not _escaped(masked, index):
                if masked[index] == "{":
                    brace_depth += 1
                elif masked[index] == "}":
                    brace_depth -= 1
        if brace_depth != 0:
            raise ManuscriptPatchError("LaTeX heading inside a brace group is ambiguous; literal top-level headings are required")
        position = match.end()
        if position < len(masked) and masked[position] == "*":
            position += 1
        while position < len(masked) and masked[position].isspace():
            position += 1
        if position < len(masked) and masked[position] == "[":
            _, position = _balanced(masked, position, "[", "]")
            while position < len(masked) and masked[position].isspace():
                position += 1
        title, end_of_title = _balanced(masked, position, "{", "}")
        starts.append((match.start(), re.sub(r"\s+", " ", title).strip()))
        scanned = end_of_title
    return starts


def _inventory(path, data, text):
    if path.suffix.lower() not in _FORMATS:
        raise ManuscriptPatchError("supported manuscript formats are .md, .markdown, and .tex")
    headings = _latex_headings(text) if path.suffix.lower() == ".tex" else _markdown_headings(text)
    points = []
    if not headings:
        points.append((0, "", "body"))
    elif headings[0][0] > 0:
        points.append((0, "", "preamble"))
    used = {point[2] for point in points}
    for start, title in headings:
        slug = re.sub(r"[^\w]+", "-", unicodedata.normalize("NFKC", title).lower(), flags=re.UNICODE).strip("-_") or "section"
        section_id, duplicate = slug, 2
        while section_id in used:
            section_id = f"{slug}-{duplicate}"
            duplicate += 1
        used.add(section_id)
        points.append((start, title, section_id))
    sections = []
    for index, (start, title, section_id) in enumerate(points):
        end = points[index + 1][0] if index + 1 < len(points) else len(text)
        sections.append({"id": section_id, "heading": title, "start": start, "end": end, "text": text[start:end]})
    return {"path": str(path), "sha256": _digest(data), "sections": sections}


def inspect_manuscript(path):
    """Return a strict UTF-8 inventory; offsets exclude an optional BOM."""
    path = _plain_path(path)
    data, text = _read(path)
    return _inventory(path, data, text)


def _strings(value, name, allow_empty=False):
    if not isinstance(value, list) or (not value and not allow_empty):
        raise ManuscriptPatchError(f"{name} must be a list" + ("" if allow_empty else " with at least one ID"))
    if any(not isinstance(item, str) or not item.strip() for item in value) or len(set(value)) != len(value):
        raise ManuscriptPatchError(f"{name} must contain unique nonempty strings")
    return value


def _dependencies(packet, manuscript, targets=None):
    dependencies = packet.get("dependencies", [])
    if not isinstance(dependencies, list):
        raise ManuscriptPatchError("dependencies must be a list")
    ids, paths = set(), {}
    for entry in dependencies:
        if not isinstance(entry, dict) or not isinstance(entry.get("id"), str) or not entry["id"].strip():
            raise ManuscriptPatchError("each dependency requires a nonempty id")
        used_by = _strings(entry.get("used_by"), "dependency.used_by", allow_empty=True)
        active = targets is None or not used_by or bool(set(used_by).intersection(targets))
        path = _plain_path(entry.get("path"), manuscript.parent, require_file=active)
        key = os.path.normcase(str(path))
        if entry["id"] in ids or path == manuscript:
            raise ManuscriptPatchError("dependency IDs must be unique and dependency paths distinct from manuscript")
        ids.add(entry["id"])
        expected = _hash(entry.get("sha256"), "dependency.sha256")
        if key in paths:
            if paths[key][1] != expected:
                raise ManuscriptPatchError("dependencies for the same path have inconsistent hashes")
            paths[key][2] = paths[key][2] or active
            continue
        paths[key] = [path, expected, active]
    return [(path, expected) for path, expected, active in paths.values() if active]


def _check_dependencies(dependencies):
    for path, expected in dependencies:
        _plain_path(path)
        try:
            actual = _digest(path.read_bytes())
        except OSError as exc:
            raise ManuscriptPatchError(f"cannot read dependency: {path}: {exc}") from exc
        if actual != expected:
            raise ManuscriptPatchError(f"dependency changed: {path}")


@contextmanager
def _exclusive_lock(path):
    lock = path.with_name(f".{path.name}.ccfa-patch.lock")
    token = f"{os.getpid()}:{secrets.token_hex(16)}".encode("ascii")
    try:
        descriptor = os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    except FileExistsError as exc:
        raise ManuscriptPatchError(f"manuscript is locked: {lock}") from exc
    except OSError as exc:
        raise ManuscriptPatchError(f"cannot lock manuscript: {exc}") from exc
    identity = os.fstat(descriptor)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(token)
            stream.flush()
        yield
    finally:
        # Track the created inode even if writing the token failed partway.
        # Never remove a lock that another actor has replaced.
        try:
            current = lock.lstat()
            if not stat.S_ISLNK(current.st_mode) and (current.st_dev, current.st_ino) == (identity.st_dev, identity.st_ino):
                lock.unlink()
        except FileNotFoundError:
            pass


def _validate_inventory(supplied, actual):
    if not isinstance(supplied, list):
        raise ManuscriptPatchError("sections must be a list of inventory entries")
    seen = set()
    for entry in supplied:
        if not isinstance(entry, dict) or not isinstance(entry.get("id"), str):
            raise ManuscriptPatchError("each inventory entry requires an id")
        section_id = entry["id"]
        if section_id in seen or section_id not in actual:
            raise ManuscriptPatchError("duplicate or unknown inventory section")
        seen.add(section_id)
        for field in ("heading", "start", "end", "text"):
            if field in entry and (type(entry[field]) is not type(actual[section_id][field]) or entry[field] != actual[section_id][field]):
                raise ManuscriptPatchError(f"stale inventory: {section_id}.{field}")


def apply_patch(packet, patch):
    """Apply literal edits only to target sections on the exact declared revision.

    Relative dependency paths are relative to the manuscript's directory. An
    optional ``sections`` list can contain all or selected inventory entries;
    supplied fields are checked, but freshly read sections determine scope.
    Dependency hashes gate edits when used_by intersects targets or is empty
    (unknown scope). Other declared dependencies retain structural/path-link
    checks but may be missing; unrelated source removal does not block a patch.
    Cross-section and figure-to-section relationships must be supplied by the
    caller; they are not inferred here. operation='review' packets are read-only.
    Returns before_sha256, after_sha256, changed_sections (document order), and
    changed. An empty edit list or literal no-op does not replace the manuscript.
    """
    if not isinstance(packet, dict) or type(packet.get("schema_version")) is not int or packet["schema_version"] != 1:
        raise ManuscriptPatchError("packet.schema_version must be 1")
    if packet.get("operation") == "review":
        raise ManuscriptPatchError("review packets are read-only and cannot patch the manuscript")
    if "operation" in packet and packet["operation"] != "write":
        raise ManuscriptPatchError("packet.operation must be write or review")
    manuscript = packet.get("manuscript")
    if not isinstance(manuscript, dict):
        raise ManuscriptPatchError("packet.manuscript must be an object")
    path = _plain_path(manuscript.get("path"))
    expected = _hash(manuscript.get("sha256"), "manuscript.sha256")
    if not isinstance(patch, dict) or _hash(patch.get("base_sha256"), "patch.base_sha256") != expected:
        raise ManuscriptPatchError("patch base does not match packet manuscript hash")
    targets = _strings(packet.get("targets"), "targets")
    edits = patch.get("edits")
    if not isinstance(edits, list):
        raise ManuscriptPatchError("patch.edits must be a list")
    dependencies = _dependencies(packet, path, targets)
    with _exclusive_lock(path):
        _plain_path(path)
        data, text = _read(path)
        if _digest(data) != expected:
            raise ManuscriptPatchError("manuscript changed since packet creation")
        inventory = _inventory(path, data, text)
        sections = {entry["id"]: entry for entry in inventory["sections"]}
        if any(target not in sections for target in targets):
            raise ManuscriptPatchError("target section does not exist in current manuscript")
        if "sections" in packet:
            _validate_inventory(packet["sections"], sections)
        _check_dependencies(dependencies)
        replacements = []
        for edit in edits:
            if not isinstance(edit, dict) or not isinstance(edit.get("section_id"), str):
                raise ManuscriptPatchError("each edit requires a section_id")
            section_id = edit["section_id"]
            if section_id not in targets:
                raise ManuscriptPatchError(f"unauthorized section: {section_id}")
            before, after = edit.get("before"), edit.get("after")
            if not isinstance(before, str) or not before or not isinstance(after, str):
                raise ManuscriptPatchError("edit.before must be nonempty text and edit.after must be text")
            section = sections[section_id]
            match = section["text"].find(before)
            # Count overlapping occurrences too: 'aa' is ambiguous inside 'aaa'.
            if match == -1 or section["text"].find(before, match + 1) != -1:
                raise ManuscriptPatchError(f"edit.before must match uniquely inside section: {section_id}")
            start = section["start"] + match
            replacements.append((start, start + len(before), after, section_id, before != after))
        replacements.sort(key=lambda item: item[0])
        for left, right in zip(replacements, replacements[1:]):
            if left[1] > right[0]:
                raise ManuscriptPatchError("overlapping edits are not allowed")
        changed_ids = {item[3] for item in replacements if item[4]}
        for start, end, after, _, _ in reversed(replacements):
            text = text[:start] + after + text[end:]
        result_data = (_BOM if data.startswith(_BOM) else b"") + text.encode("utf-8")
        result_hash = _digest(result_data)
        result = {"before_sha256": expected, "after_sha256": result_hash,
                  "changed_sections": [entry["id"] for entry in inventory["sections"] if entry["id"] in changed_ids],
                  "changed": result_data != data}
        if not result["changed"]:
            result["changed_sections"] = []
            return result
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(mode="wb", prefix=f".{path.name}.ccfa-", suffix=".tmp", dir=path.parent, delete=False) as stream:
                temporary = Path(stream.name)
                stream.write(result_data)
                stream.flush()
                os.fsync(stream.fileno())
            os.chmod(temporary, stat.S_IMODE(path.stat().st_mode))
            _plain_path(path)
            if _digest(path.read_bytes()) != expected:
                raise ManuscriptPatchError("manuscript changed while patch was prepared")
            _check_dependencies(dependencies)
            os.replace(temporary, path)
            temporary = None
        finally:
            if temporary is not None:
                temporary.unlink(missing_ok=True)
        return result
